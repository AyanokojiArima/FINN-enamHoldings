// ============================================================================ search home
export default function Research({ symbol, setSymbol, picks, portfolio }: {
  symbol: string | null; setSymbol: (s: string | null) => void; picks: string[]; portfolio: string[];
}) {
  if (symbol) return <DossierView key={symbol} symbol={symbol} onBack={() => setSymbol(null)} />;
  return <SearchHome onPick={setSymbol} picks={picks} portfolio={portfolio} />;
}

function SearchHome({ onPick, picks, portfolio }: { onPick: (s: string) => void; picks: string[]; portfolio: string[] }) {
  const [q, setQ] = useState("");
  const [hits, setHits] = useState<{ symbol: string; name: string }[]>([]);
  useEffect(() => {
    if (!q.trim()) { setHits([]); return; }
    const t = setTimeout(() => api.search(q).then(setHits).catch(() => setHits([])), 180);
    return () => clearTimeout(t);
  }, [q]);
  return (
    <div className="pb-28">
      <div className="mt-2 text-[26px] font-semibold leading-tight tracking-tight">Research any NSE stock.</div>
      <p className="mt-1 text-[14px] text-mute">Built only from filings, annual reports and earnings-call transcripts. Every claim shows its receipt.</p>
      <div className="relative mt-4">
        <Search size={17} className="absolute left-3.5 top-1/2 -translate-y-1/2 text-mute" />
        <input autoFocus value={q} onChange={(e) => setQ(e.target.value)}
          onKeyDown={(e) => e.key === "Enter" && (hits[0] ? onPick(hits[0].symbol) : q.trim() && onPick(q.trim().toUpperCase()))}
          placeholder="Ticker or company - e.g. DIXON, Titan"
          className="w-full rounded-2xl border hairline bg-ink-850 py-3.5 pl-10 pr-4 text-[15px] outline-none placeholder:text-dim focus:border-fin/50" />
        {hits.length > 0 && (
          <div className="card absolute left-0 right-0 top-[calc(100%+6px)] z-30 overflow-hidden bg-ink-900">
            {hits.map((h) => (
              <button key={h.symbol} onClick={() => onPick(h.symbol)} className="flex w-full items-baseline gap-3 px-4 py-2.5 text-left hover:bg-white/[0.04]">
                <b className="text-[13px]">{h.symbol}</b><span className="truncate text-[13px] text-mute">{h.name}</span>
              </button>
            ))}
          </div>
        )}
      </div>
      <SectionTitle>Try these</SectionTitle>
      <div className="flex flex-wrap gap-2">
        {picks.map((s) => <button key={s} onClick={() => onPick(s)} className="rounded-full border border-fin/30 bg-fin/[0.07] px-3.5 py-1.5 text-[13px] font-semibold text-fin">{s}</button>)}
      </div>
      <SectionTitle>Your portfolio</SectionTitle>
      <div className="flex flex-wrap gap-2">
        {portfolio.map((s) => <button key={s} onClick={() => onPick(s)} className="rounded-full bg-white/[0.05] px-3 py-1.5 text-[13px] text-white/80 hover:text-white">{s}</button>)}
      </div>
      <div className="card mt-6 space-y-2 p-4 text-[13px] text-mute">
        <div className="flex gap-2"><Check size={15} className="mt-0.5 shrink-0 text-fin" /> Numbers are computed in code from company filings - never generated by a model.</div>
        <div className="flex gap-2"><Check size={15} className="mt-0.5 shrink-0 text-fin" /> AI reads the last four earnings calls; every quote is verified against the transcript.</div>
        <div className="flex gap-2"><Check size={15} className="mt-0.5 shrink-0 text-fin" /> No news, broker notes or model memory - primary sources only.</div>
      </div>
    </div>
  );
}

