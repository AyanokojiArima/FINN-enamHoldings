// ---------------------------------------------------------------------------- ask
function Ask({ symbol, onReceipt }: { symbol: string; onReceipt: (r: Receipt) => void }) {
  const [q, setQ] = useState("");
  const [busy, setBusy] = useState(false);
  const [thread, setThread] = useState<{ q: string; a: AskAnswer }[]>([]);
  const [mic, setMic] = useState(false);
  const stop = useRef<() => void>(() => {});
  const suggestions = ["What did management guide for margins?", "Why did growth slow?", "What is the capex plan?"];

  const send = async (text = q) => {
    if (!text.trim() || busy) return;
    setBusy(true);
    try {
      const a = await api.ask(symbol, text);
      setThread((t) => [...t, { q: text, a }]);
      setQ("");
    } catch (e) {
      setThread((t) => [...t, { q: text, a: { answer: `Couldn't answer: ${e}`, method: "error", sources: [] } }]);
    } finally {
      setBusy(false);
    }
  };

  const toggleMic = () => {
    if (mic) { stop.current(); setMic(false); return; }
    setMic(true);
    stop.current = listen((t) => setQ(t), () => setMic(false));
  };

  return (
    <>
      <SectionTitle id="ask">Ask the filings</SectionTitle>
      <div className="card p-4">
        {thread.length === 0 && (
          <div className="mb-3 flex flex-wrap gap-1.5">
            {suggestions.map((s) => <button key={s} onClick={() => send(s)} className="rounded-full bg-white/[0.05] px-3 py-1.5 text-[12px] text-mute hover:text-white">{s}</button>)}
          </div>
        )}
        <div className="space-y-4">
          {thread.map((m, i) => (
            <div key={i} className="space-y-2">
              <div className="ml-auto w-fit max-w-[85%] rounded-2xl rounded-br-md bg-fin/15 px-3 py-2 text-[13px]">{m.q}</div>
              <div className="text-[13.5px] leading-relaxed">{m.a.answer}</div>
              <div className="flex flex-wrap gap-1.5">
                {m.a.sources.map((s) => (
                  <button key={s.id} onClick={() => onReceipt({ title: s.label, quote: s.text, url: s.url, page: Number(s.id.split("p.")[1]) || undefined })}
                    className="rounded-full bg-white/[0.06] px-2 py-0.5 text-[11px] text-mute hover:text-fin">{s.id}</button>
                ))}
              </div>
            </div>
          ))}
        </div>
        <div className="mt-3 flex items-center gap-2 rounded-2xl border hairline bg-ink-850 p-1.5 pl-3">
          <input value={q} onChange={(e) => setQ(e.target.value)} onKeyDown={(e) => e.key === "Enter" && send()}
            placeholder={`Ask about ${symbol}…`} className="flex-1 bg-transparent text-[14px] outline-none placeholder:text-dim" />
          {q && <button onClick={() => setQ("")} className="p-1 text-dim" aria-label="Clear"><X size={14} /></button>}
          {canListen() && (
            <button onClick={toggleMic} className={cls("rounded-full p-2", mic ? "bg-down/20 text-down" : "text-mute hover:text-white")} aria-label="Voice">
              {mic ? <MicOff size={16} /> : <Mic size={16} />}
            </button>
          )}
          <button onClick={() => send()} disabled={busy} className="rounded-xl bg-fin p-2 text-ink-950 disabled:opacity-50" aria-label="Send">
            {busy ? <Loader2 size={16} className="animate-spin" /> : <Send size={16} />}
          </button>
        </div>
        <p className="mt-2 text-[11px] text-dim">Answers come only from this company's transcripts and filings, with citations.</p>
      </div>
    </>
  );
}
